//    방향 정보가 색에 없다 — "내려오는 흐름" 은 그 그림에서 확인되지 않는다.
// 10. 작업 편의를 성과로 팔지 않는다 (multi-leg 재작성에서 얻은 규칙).
//     ⚠️ "이렇게 하니 빨랐다" 도 같은 프레임이다. 게다가 §03 본문이 "값을 먼저 만졌다" 고
//     적고 있어 "먼저 가렸다" 는 사실과도 반대였다.
// 11. **검증 없는 확장성 주장을 쓰지 않는다.** 두 번째 가연물을 만든 적이 없다.
//
// ─── 문장 규칙 ───────────────────────────────────────────
