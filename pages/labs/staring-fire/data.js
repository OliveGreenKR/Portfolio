//    `60 Hz`(Unity 고정 timestep = 입력값) · `~47 dispatch`(구조에서 도출) ·
//    `N 번째 클릭까지 발산 없음`(N 미정의) 은 전부 버렸다.
//    ⚠️ 단, **파이프라인 단계 순서와 격자 크기는 계측이 아니라 구조 사실**이라 남긴다.
// 3. 지어낸 baseline 을 만들지 않는다. (`"가상의 직결합 / 튜닝 baseline"` 표 7행 삭제.)
// 4. 규모를 성과로 세우지 않는다. 커밋 29 · C# 16 파일 · ~3,300 LoC 는 히어로에 안 올린다.
// 5. **표준과 내가 정한 것을 가른다.** 유체 계산 · 소용돌이 보정 · 연소 · 열린 경계는 알려진 방법이다.
//    정한 것은 **게이트의 형태 · 어디를 열지 · 창구를 몇 개 둘지** 셋이고,
//    ⚠️ 이 셋은 주석에만 있으면 안 된다 — `facts` 에 독자가 읽는 행으로 둔다.
// 6. **흑체 복사 변환은 인용한 코드다** (zubetto/BlackBodyRadiation, MIT).
//    히어로 칸에서도 그 사실을 밝힌다 — §01 까지 내려가서야 나오면 늦다.
// 7. **`6 MB` 를 쓰지 않는다.** "MonoBehaviour 여섯"을 줄인 것인데 메가바이트로 읽힌다.
// 8. **캡처 넷은 같은 순간이 아니다.** 방 온도가 각각 207 / 483 / 536 / 533 °C 다.
//    ⚠️ 캡션이 서로 다른 캡처를 가로질러 비교하지 않게 한다 — 그러면 이 규칙을 스스로 어긴다.
